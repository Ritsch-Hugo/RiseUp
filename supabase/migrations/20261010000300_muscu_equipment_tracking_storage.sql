-- Photos perso : bucket privé, un dossier par utilisateur (<user_id>/<exercise_id>.jpg), accès par URL signée.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('exercise-images', 'exercise-images', false, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do nothing;

create policy "exercise-images owner" on storage.objects
  for all to authenticated
  using (bucket_id = 'exercise-images' and (storage.foldername(name))[1] = auth.uid()::text)
  with check (bucket_id = 'exercise-images' and (storage.foldername(name))[1] = auth.uid()::text);
